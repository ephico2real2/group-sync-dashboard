"""The ticket key (#392, docs/specs/SPEC_F6_ticket_signing_key.md): viewers' tickets are signed with a key of their
own, never with the service token the schedule Jobs and the poller hold, so a token holder can no longer sign a
ticket naming anybody and make that name a run's "Generated by". T392-1 to T392-7, one per rule of SPEC_F6 §4.1."""

